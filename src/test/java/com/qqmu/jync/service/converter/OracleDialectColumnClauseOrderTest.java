package com.qqmu.jync.service.converter;

import static org.assertj.core.api.Assertions.assertThat;

import java.sql.Types;
import java.util.List;

import org.junit.jupiter.api.Test;

import com.qqmu.jync.dto.meta.ColumnMeta;
import com.qqmu.jync.dto.meta.TableMeta;
import com.qqmu.jync.model.DatabaseType;

/**
 * Oracle's column grammar is {@code name type [DEFAULT expr] [inline_constraint ...]} — the
 * default must come BEFORE {@code NOT NULL}. Copying MySQL's order
 * ({@code "STATUS" NUMBER(3) NOT NULL DEFAULT 0}) makes Oracle's parser meet {@code DEFAULT}
 * where it expects a comma or the closing paren: ORA-00907 "missing right parenthesis" before
 * 23ai, ORA-03076 "unexpected item DEFAULT in column definition" on 23ai.
 */
class OracleDialectColumnClauseOrderTest {

    private final OracleDialect oracle = new OracleDialect(23);

    @Test
    void notNullColumnWithDefaultPlacesDefaultBeforeNotNull() {
        TableMeta table = new TableMeta();
        table.setName("t_location");
        table.setColumns(List.of(
                bigint("LOCATION_ID", false, "0"),
                character("LOCATION_NO", false, "'N/A'"),
                tinyint("STATUS", false, "0"),
                tinyint("ZONE_ID", true, "0")));
        table.setPrimaryKeys(List.of("LOCATION_ID"));

        String ddl = oracle.getCreateTableSql(table, null, "T_LOCATION", DatabaseType.MYSQL);

        assertThat(ddl)
                .contains("\"STATUS\" NUMBER(3) DEFAULT 0 NOT NULL")
                .contains("\"LOCATION_NO\" VARCHAR2(100 CHAR) DEFAULT 'N/A' NOT NULL");
        assertThat(ddl)
                .as("Oracle rejects the MySQL NOT-NULL-then-DEFAULT order with ORA-00907")
                .doesNotContain("NOT NULL DEFAULT");
    }

    /**
     * A nullable column only loses the NOT NULL, so the default still has to land in the one
     * legal position — a misplaced clause here is the same ORA-00907.
     */
    @Test
    void nullableColumnWithDefaultKeepsTheDefault() {
        TableMeta table = new TableMeta();
        table.setName("t_location");
        table.setColumns(List.of(bigint("ZONE_ID", true, "0")));

        String ddl = oracle.getCreateTableSql(table, null, "T_LOCATION", DatabaseType.MYSQL);

        assertThat(ddl).contains("\"ZONE_ID\" NUMBER(19) DEFAULT 0");
        assertThat(ddl).doesNotContain("NOT NULL");
    }

    /**
     * The identity clause keeps its own required order: a 12c identity column takes
     * {@code NOT NULL} after {@code AS IDENTITY} and must not grow a default.
     */
    @Test
    void identityColumnKeepsNotNullAfterTheIdentityClause() {
        TableMeta table = new TableMeta();
        table.setName("t_location");
        ColumnMeta id = bigint("LOCATION_ID", false, "0");
        id.setAutoIncrement(true);
        table.setColumns(List.of(id));
        table.setPrimaryKeys(List.of("LOCATION_ID"));

        String ddl = oracle.getCreateTableSql(table, null, "T_LOCATION", DatabaseType.MYSQL);

        assertThat(ddl)
                .contains("NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL")
                .as("the sequence default of an auto-increment column must not be copied")
                .doesNotContain("DEFAULT 0");
    }

    private static ColumnMeta character(String name, boolean nullable, String defaultValue) {
        ColumnMeta c = new ColumnMeta();
        c.setName(name);
        c.setJdbcType(Types.VARCHAR);
        c.setSize(100);
        c.setNullable(nullable);
        c.setDefaultValue(defaultValue);
        return c;
    }

    private static ColumnMeta bigint(String name, boolean nullable, String defaultValue) {
        ColumnMeta c = new ColumnMeta();
        c.setName(name);
        c.setJdbcType(Types.BIGINT);
        c.setSize(19);
        c.setNullable(nullable);
        c.setDefaultValue(defaultValue);
        return c;
    }

    private static ColumnMeta tinyint(String name, boolean nullable, String defaultValue) {
        ColumnMeta c = new ColumnMeta();
        c.setName(name);
        c.setJdbcType(Types.TINYINT);
        c.setSize(3);
        c.setNullable(nullable);
        c.setDefaultValue(defaultValue);
        return c;
    }
}
