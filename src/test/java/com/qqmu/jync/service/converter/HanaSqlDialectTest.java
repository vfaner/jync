package com.qqmu.jync.service.converter;

import static org.assertj.core.api.Assertions.assertThat;

import java.sql.Types;
import java.util.ArrayList;
import java.util.List;

import org.junit.jupiter.api.Test;

import com.qqmu.jync.dto.meta.ColumnMeta;
import com.qqmu.jync.dto.meta.ProcedureMeta;
import com.qqmu.jync.dto.meta.TableMeta;
import com.qqmu.jync.dto.meta.ViewMeta;
import com.qqmu.jync.model.DatabaseType;

/**
 * SAP HANA rejects three shapes the generic dialect emits: the SQL:2008 pagination tail,
 * the ANSI column-alter forms and a plain INSERT where an idempotent upsert is required.
 * Every assertion here is a statement verified against HANA Express 2.00.082.
 */
class HanaSqlDialectTest {

    private final HanaSqlDialect dialect = new HanaSqlDialect();

    @Test
    void declaresTheHanaFamily() {
        assertThat(dialect.family()).isEqualTo(DatabaseType.DialectFamily.HANA);
    }

    @Test
    void identifiersAreDoubleQuotedAndCaseIsPreserved() {
        assertThat(dialect.qualify("JC_PROBE", "T_GEN2")).isEqualTo("\"JC_PROBE\".\"T_GEN2\"");
        assertThat(dialect.quoteIdentifier("MixEd")).isEqualTo("\"MixEd\"");
    }

    @Test
    void paginationUsesLimitOffset() {
        assertThat(dialect.getPaginationSql(
                "SELECT \"ID\" FROM \"JC_PROBE\".\"T\" ORDER BY \"ID\"", 20, 10))
                .isEqualTo("SELECT \"ID\" FROM \"JC_PROBE\".\"T\" ORDER BY \"ID\" LIMIT 10 OFFSET 20");
    }

    @Test
    void aKeylessTableFallsBackToAPlainInsert() {
        // WITH PRIMARY KEY is rejected by HANA when the target has no primary key, so the
        // keyless caller (which has no idempotent option anyway) must get a plain INSERT.
        assertThat(dialect.getUpsertSql("JC_PROBE", "T", List.of("ID", "NAME"), List.of()))
                .isEqualTo("INSERT INTO \"JC_PROBE\".\"T\" (\"ID\", \"NAME\") VALUES (?, ?)");
    }

    @Test
    void upsertUsesHanasNativeUpsertWithPrimaryKey() {
        assertThat(dialect.getUpsertSql("JC_PROBE", "T", List.of("ID", "NAME"), List.of("ID")))
                .isEqualTo("UPSERT \"JC_PROBE\".\"T\" (\"ID\", \"NAME\") VALUES (?, ?)"
                        + " WITH PRIMARY KEY");
    }

    @Test
    void upsertBindOrderIsTheColumnOrder() {
        assertThat(dialect.upsertBindOrder(List.of("ID", "NAME"), List.of("ID")))
                .containsExactly("ID", "NAME");
    }

    @Test
    void columnChangesUseHanasParenthesisedAlterForms() {
        ColumnMeta name = column("NAME", Types.VARCHAR, 100);

        assertThat(dialect.getModifyColumnSql("S", "T", name, DatabaseType.MYSQL))
                .isEqualTo("ALTER TABLE \"S\".\"T\" ALTER (\"NAME\" VARCHAR(100))");
        assertThat(dialect.getAddColumnSql("S", "T", name, DatabaseType.MYSQL))
                .isEqualTo("ALTER TABLE \"S\".\"T\" ADD (\"NAME\" VARCHAR(100))");
        assertThat(dialect.getDropColumnSql("S", "T", "NAME"))
                .isEqualTo("ALTER TABLE \"S\".\"T\" DROP (\"NAME\")");
    }

    @Test
    void anIdentityColumnIsCreatedWithHanasIdentityClause() {
        ColumnMeta id = column("ID", Types.INTEGER, null);
        id.setNullable(false);
        id.setAutoIncrement(true);

        TableMeta table = new TableMeta();
        table.setName("T");
        table.setColumns(new ArrayList<>(List.of(id)));
        table.setPrimaryKeys(List.of("ID"));

        assertThat(dialect.getCreateTableSql(table, "S", "T", DatabaseType.HANA))
                .contains("\"ID\" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL")
                .contains("PRIMARY KEY (\"ID\")");
    }

    private static ColumnMeta column(String name, int jdbcType, Integer size) {
        ColumnMeta c = new ColumnMeta();
        c.setName(name);
        c.setJdbcType(jdbcType);
        c.setSize(size);
        c.setNullable(true);
        return c;
    }

    @Test
    void viewsAreReplacedInPlaceBecauseHanaHasNoDropIfExists() {
        ViewMeta view = new ViewMeta();
        view.setName("V_USER");
        view.setDefinition("SELECT \"ID\" FROM \"S\".\"T_USER\";");

        assertThat(dialect.getCreateViewSql(view, "S", DatabaseType.HANA))
                .containsExactly("CREATE OR REPLACE VIEW \"S\".\"V_USER\" AS "
                        + "SELECT \"ID\" FROM \"S\".\"T_USER\"");
        assertThat(dialect.dropsBeforeViewCreate()).isFalse();
    }

    @Test
    void routineDefinitionsAreRewrittenToCreateOrReplace() {
        ProcedureMeta proc = new ProcedureMeta();
        proc.setName("P_ADD");
        proc.setDefinition("CREATE PROCEDURE \"S\".\"P_ADD\" (IN a INTEGER, OUT c INTEGER) "
                + "LANGUAGE SQLSCRIPT AS BEGIN c := :a; END");

        assertThat(dialect.getCreateProcedureSql(proc, "S", DatabaseType.HANA))
                .containsExactly("CREATE OR REPLACE PROCEDURE \"S\".\"P_ADD\" "
                        + "(IN a INTEGER, OUT c INTEGER) "
                        + "LANGUAGE SQLSCRIPT AS BEGIN c := :a; END");

        ProcedureMeta fn = new ProcedureMeta();
        fn.setName("F_ADD");
        fn.setRoutineType("FUNCTION");
        fn.setDefinition("CREATE FUNCTION \"S\".\"F_ADD\" (a INTEGER) RETURNS c INTEGER "
                + "LANGUAGE SQLSCRIPT AS BEGIN c := :a; END");

        assertThat(dialect.getCreateProcedureSql(fn, "S", DatabaseType.HANA))
                .containsExactly("CREATE OR REPLACE FUNCTION \"S\".\"F_ADD\" (a INTEGER) "
                        + "RETURNS c INTEGER LANGUAGE SQLSCRIPT AS BEGIN c := :a; END");
    }

    @Test
    void aDefinitionWithoutABodyProducesNoStatement() {
        ProcedureMeta empty = new ProcedureMeta();
        empty.setName("P_EMPTY");

        assertThat(dialect.getCreateProcedureSql(empty, "S", DatabaseType.HANA)).isEmpty();
    }

    @Test
    void tableCommentsUseCommentOnAndClearWithNull() {
        assertThat(dialect.getAlterTableCommentSql("S", "T", "it's a comment"))
                .isEqualTo("COMMENT ON TABLE \"S\".\"T\" IS 'it''s a comment'");
        assertThat(dialect.getAlterTableCommentSql("S", "T", "  "))
                .isEqualTo("COMMENT ON TABLE \"S\".\"T\" IS NULL");
    }

    @Test
    void theFactoryRoutesHanaAndAHanaDeclaredCustomConnectionToThisDialect() {
        SqlDialectFactory factory = new SqlDialectFactory(
                List.of(new HanaSqlDialect(), new GenericSqlDialect()), new GenericSqlDialect());

        assertThat(factory.forType(DatabaseType.HANA)).isInstanceOf(HanaSqlDialect.class);
        assertThat(factory.forType(DatabaseType.CUSTOM, null,
                DatabaseType.DialectFamily.HANA)).isInstanceOf(HanaSqlDialect.class);
    }
}
