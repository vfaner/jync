package com.qqmu.jync.service.converter;

import static org.assertj.core.api.Assertions.assertThat;

import java.sql.Types;
import java.util.ArrayList;
import java.util.List;

import org.junit.jupiter.api.Test;

import com.qqmu.jync.dto.meta.ColumnMeta;
import com.qqmu.jync.dto.meta.TableMeta;
import com.qqmu.jync.model.DatabaseType;

/**
 * DM8 has a native {@code AUTO_INCREMENT} column attribute that — unlike {@code IDENTITY} —
 * accepts explicit values, so a MySQL auto-increment id can be written as-is while the target
 * dictionary still reports the column as auto-increment. It is only legal on an integer
 * column that is part of the primary key; everything else keeps the sequence+trigger
 * emulation. Verified on DM8 8.1.2.128 (see docs/dm-logminer-spike.md).
 */
class DmAutoIncrementDialectTest {

    private final OracleDialect dm =
            (OracleDialect) new OracleDialect(11).forProduct(DatabaseType.DM);
    private final OracleDialect oracle =
            (OracleDialect) new OracleDialect(23).forProduct(DatabaseType.ORACLE);

    @Test
    void aPrimaryKeyAutoIncrementColumnUsesDmNativeAutoIncrement() {
        TableMeta table = table(autoIncrementId(Types.BIGINT), List.of("id"));

        String ddl = dm.getCreateTableSql(table, null, "orders", DatabaseType.MYSQL);

        assertThat(ddl).contains("\"ID\" BIGINT AUTO_INCREMENT NOT NULL");
        assertThat(ddl).doesNotContain("NUMBER(19)").doesNotContain("AS IDENTITY");
        assertThat(dm.getPostCreateTableDdl(table, null, "orders", DatabaseType.MYSQL)).isEmpty();
        assertThat(dm.hasNativeAutoIncrement(table.getColumns().get(0))).isTrue();
    }

    @Test
    void narrowerIntegerKeysStayInsideDmAutoIncrementIntegerTypes() {
        TableMeta table = table(autoIncrementId(Types.INTEGER), List.of("id"));

        assertThat(dm.getCreateTableSql(table, null, "orders", DatabaseType.MYSQL))
                .contains("\"ID\" INT AUTO_INCREMENT");
    }

    @Test
    void aNonKeyAutoIncrementColumnKeepsTheSequenceAndTrigger() {
        ColumnMeta id = autoIncrementId(Types.BIGINT);
        id.setPrimaryKey(false);
        TableMeta table = table(id, List.of("other"));

        String ddl = dm.getCreateTableSql(table, null, "orders", DatabaseType.MYSQL);

        assertThat(ddl).doesNotContain("AUTO_INCREMENT");
        List<String> extra = dm.getPostCreateTableDdl(table, null, "orders",
                DatabaseType.MYSQL);
        assertThat(extra).hasSize(2);
        assertThat(extra.get(0).toUpperCase()).contains("CREATE SEQUENCE");
        assertThat(extra.get(1).toUpperCase()).contains("CREATE OR REPLACE TRIGGER");
    }

    @Test
    void aNonIntegerAutoIncrementColumnKeepsTheSequenceAndTrigger() {
        // DM rejects AUTO_INCREMENT on NUMBER(n): "无效的数据类型". Oracle-family sources
        // report auto-increment NUMBER columns as NUMERIC, so they must fall back.
        ColumnMeta id = autoIncrementId(Types.NUMERIC);
        id.setTypeName("NUMBER");
        id.setSize(19);
        TableMeta table = table(id, List.of("id"));

        assertThat(dm.getCreateTableSql(table, null, "orders", DatabaseType.MYSQL))
                .doesNotContain("AUTO_INCREMENT");
        assertThat(dm.getPostCreateTableDdl(table, null, "orders", DatabaseType.MYSQL))
                .isNotEmpty();
    }

    @Test
    void aCompositePrimaryKeyMemberStillQualifies() {
        ColumnMeta id = autoIncrementId(Types.BIGINT);
        ColumnMeta tenant = column("tenant", Types.INTEGER, "INT", false);
        TableMeta table = table(id, tenant, List.of("tenant", "id"));

        assertThat(dm.getCreateTableSql(table, null, "orders", DatabaseType.MYSQL))
                .contains("\"ID\" BIGINT AUTO_INCREMENT");
    }

    @Test
    void addingTheColumnLaterNeverEmitsAutoIncrement() {
        // DM requires AUTO_INCREMENT to be part of the primary key at creation; an ALTER ADD
        // cannot satisfy that, so the plain type is added and the trigger takes over.
        ColumnMeta id = autoIncrementId(Types.BIGINT);

        assertThat(dm.getAddColumnSql(null, "orders", id, DatabaseType.MYSQL))
                .doesNotContain("AUTO_INCREMENT");
        assertThat(dm.getPostColumnChangeDdl(null, "orders", id, DatabaseType.MYSQL))
                .hasSize(2);
    }

    @Test
    void oracleItselfIsUnaffected() {
        TableMeta table = table(autoIncrementId(Types.BIGINT), List.of("id"));

        String ddl = oracle.getCreateTableSql(table, null, "orders", DatabaseType.MYSQL);

        assertThat(ddl).contains("GENERATED BY DEFAULT ON NULL AS IDENTITY");
        assertThat(ddl).doesNotContain("AUTO_INCREMENT");
    }

    private static TableMeta table(ColumnMeta id, List<String> primaryKeys) {
        return table(id, column("name", Types.VARCHAR, "VARCHAR", true), primaryKeys);
    }

    private static TableMeta table(ColumnMeta first, ColumnMeta second, List<String> primaryKeys) {
        TableMeta table = new TableMeta();
        table.setName("orders");
        table.setColumns(new ArrayList<>(List.of(first, second)));
        table.setPrimaryKeys(primaryKeys);
        return table;
    }

    private static ColumnMeta autoIncrementId(int jdbcType) {
        ColumnMeta id = column("id", jdbcType, "BIGINT", false);
        id.setAutoIncrement(true);
        id.setPrimaryKey(true);
        id.setOrdinalPosition(1);
        return id;
    }

    private static ColumnMeta column(String name, int jdbcType, String typeName,
                                     boolean nullable) {
        ColumnMeta column = new ColumnMeta();
        column.setName(name);
        column.setJdbcType(jdbcType);
        column.setTypeName(typeName);
        column.setSize(19);
        column.setNullable(nullable);
        column.setOrdinalPosition(2);
        return column;
    }
}
