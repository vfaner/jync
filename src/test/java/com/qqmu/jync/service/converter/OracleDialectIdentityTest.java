package com.qqmu.jync.service.converter;

import static org.assertj.core.api.Assertions.assertThat;

import java.sql.Types;
import java.util.ArrayList;
import java.util.List;

import org.junit.jupiter.api.Test;

import com.qqmu.jync.dto.meta.ColumnMeta;
import com.qqmu.jync.dto.meta.TableMeta;
import com.qqmu.jync.model.DatabaseType;

/**
 * Oracle-family target conventions:
 * <ul>
 *   <li>identifiers fold to upper case, so a MySQL/PostgreSQL-style lowercase source table
 *       lands on the conventional Oracle object instead of a quoted lowercase twin;</li>
 *   <li>identity columns use 12c {@code GENERATED ... AS IDENTITY}, with a sequence+trigger
 *       fallback for pre-12 targets;</li>
 *   <li>MODIFY keeps the identity property, and post-load sequence reseed DDL is available.</li>
 * </ul>
 */
class OracleDialectIdentityTest {

    private final OracleDialect oracle12 = new OracleDialect(23);
    private final OracleDialect oracle11 =
            (OracleDialect) new OracleDialect().withServerMajorVersion(11);

    @Test
    void identifiersFoldToUpperCaseEvenWhenQuoted() {
        // "orders" quoted-upper is the SAME object as unquoted ORDERS in Oracle, while a
        // quoted "orders" would create a second table next to a hand-created ORDERS.
        assertThat(oracle12.quoteIdentifier("orders")).isEqualTo("\"ORDERS\"");
        assertThat(oracle12.quoteIdentifier("cust_name")).isEqualTo("\"CUST_NAME\"");
        assertThat(oracle12.qualify("myschema", "orders")).isEqualTo("\"MYSCHEMA\".\"ORDERS\"");
    }

    @Test
    void createTableWithLowercaseSourceNamesFoldsEveryIdentifier() {
        TableMeta table = tableWithIdentity();
        String ddl = oracle12.getCreateTableSql(table, "orcl", "orders", DatabaseType.MYSQL);

        assertThat(ddl).contains("CREATE TABLE \"ORCL\".\"ORDERS\"");
        assertThat(ddl).contains("\"ID\"").contains("\"CUST_NAME\"");
        assertThat(ddl).contains("PRIMARY KEY (\"ID\")");
        assertThat(ddl).doesNotContain("\"orders\"").doesNotContain("\"cust_name\"");
    }

    @Test
    void modernTargetUses12cIdentityClauseAndNeedsNoExtraDdl() {
        TableMeta table = tableWithIdentity();
        String ddl = oracle12.getCreateTableSql(table, null, "orders", DatabaseType.MYSQL);

        assertThat(ddl).contains("NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY");
        assertThat(oracle12.getPostCreateTableDdl(table, null, "orders", DatabaseType.MYSQL))
                .isEmpty();
    }

    @Test
    void preTwelveTargetCreatesPlainColumnPlusSequenceAndTrigger() {
        TableMeta table = tableWithIdentity();
        String ddl = oracle11.getCreateTableSql(table, null, "orders", DatabaseType.MYSQL);
        assertThat(ddl).doesNotContain("AS IDENTITY");
        assertThat(ddl).contains("\"ID\" NUMBER(19)");

        List<String> extra = oracle11.getPostCreateTableDdl(table, null, "orders",
                DatabaseType.MYSQL);
        assertThat(extra).hasSize(2);
        String sequenceDdl = extra.get(0).toUpperCase();
        String triggerDdl = extra.get(1).toUpperCase();
        assertThat(sequenceDdl).contains("CREATE SEQUENCE").contains("START WITH 1");
        assertThat(triggerDdl).contains("CREATE OR REPLACE TRIGGER")
                .contains("BEFORE INSERT ON \"ORDERS\"")
                .contains(":NEW.\"ID\"").contains(".NEXTVAL");
        // Pre-12.2 identifier limit is 30 bytes — generated names must respect it.
        for (String stmt : extra) {
            for (String token : stmt.split("[\\s\\.\"]+")) {
                assertThat(token.length()).as("generated name within 30 chars: %s", token)
                        .isLessThanOrEqualTo(30);
            }
        }
    }

    @Test
    void modifyColumnKeepsIdentityOnModernOracleAndEmitsFallbackOnOld() {
        ColumnMeta id = identityId();
        String modern = oracle12.getModifyColumnSql(null, "orders", id, DatabaseType.MYSQL);
        assertThat(modern.toUpperCase()).contains("AS IDENTITY");
        assertThat(oracle12.getPostColumnChangeDdl(null, "orders", id, DatabaseType.MYSQL))
                .isEmpty();

        String legacy = oracle11.getModifyColumnSql(null, "orders", id, DatabaseType.MYSQL);
        assertThat(legacy.toUpperCase()).doesNotContain("AS IDENTITY");
        List<String> extra = oracle11.getPostColumnChangeDdl(null, "orders", id,
                DatabaseType.MYSQL);
        assertThat(extra).hasSize(2);
        assertThat(extra.get(0).toUpperCase()).contains("CREATE SEQUENCE");
        assertThat(extra.get(1).toUpperCase()).contains("CREATE OR REPLACE TRIGGER");
    }

    @Test
    void reseedDdlAdvancesIdentityPastTheLoadedRows() {
        ColumnMeta id = identityId();
        List<String> modern = oracle12.getIdentityReseedDdl(null, "orders", id, 4097L);
        assertThat(modern).hasSize(1);
        assertThat(modern.get(0).toUpperCase())
                .contains("ALTER TABLE \"ORDERS\"")
                .contains("MODIFY (\"ID\"")
                .contains("START WITH 4097");

        List<String> legacy = oracle11.getIdentityReseedDdl(null, "orders", id, 4097L);
        String joined = String.join("\n", legacy).toUpperCase();
        assertThat(joined).contains("DROP SEQUENCE").contains("CREATE SEQUENCE")
                .contains("START WITH 4097").contains("CREATE OR REPLACE TRIGGER");

        assertThat(oracle12.getMaxValueSql(null, "orders", "id"))
                .isEqualTo("SELECT MAX(\"ID\") FROM \"ORDERS\"");
    }

    private static TableMeta tableWithIdentity() {
        ColumnMeta id = identityId();
        ColumnMeta name = new ColumnMeta();
        name.setName("cust_name");
        name.setJdbcType(Types.VARCHAR);
        name.setTypeName("VARCHAR");
        name.setSize(50);
        name.setNullable(true);
        name.setOrdinalPosition(2);
        TableMeta table = new TableMeta();
        table.setName("orders");
        table.setColumns(new ArrayList<>(List.of(id, name)));
        table.setPrimaryKeys(List.of("id"));
        return table;
    }

    private static ColumnMeta identityId() {
        ColumnMeta id = new ColumnMeta();
        id.setName("id");
        id.setJdbcType(Types.BIGINT);
        id.setTypeName("BIGINT");
        id.setSize(19);
        id.setNullable(false);
        id.setPrimaryKey(true);
        id.setAutoIncrement(true);
        id.setOrdinalPosition(1);
        return id;
    }
}
