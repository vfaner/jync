package com.qqmu.jync.config;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatCode;

import java.util.Arrays;
import java.util.stream.Collectors;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import com.qqmu.jync.model.AuditAction;

/**
 * An install created before {@link AuditAction} gained a constant stores
 * {@code audit_event.action} as a native ENUM. Hibernate's {@code ddl-auto=update} never
 * widens an existing enum column, so the first insert of a newer constant fails (H2 error
 * 22030) — saving the alert or external-auth settings answers 500 although its own table
 * accepted the change. The migration converts that one column to text, which also means the
 * next constant needs no migration at all.
 */
class AuditActionEnumMigrationTest {

    private JdbcTemplate jdbcTemplate;
    private AuditActionEnumMigration migration;

    @BeforeEach
    void setUp() {
        // A private in-memory database per test: the migration alters a real schema, and H2
        // commits DDL immediately, so sharing one database would leak the change.
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:audit-enum-" + System.nanoTime() + ";MODE=MySQL;DB_CLOSE_DELAY=-1",
                "sa", "");
        jdbcTemplate = new JdbcTemplate(dataSource);
        migration = new AuditActionEnumMigration(jdbcTemplate);
    }

    /** The schema of a release whose AuditAction did not yet know the two newest constants. */
    private void createSchemaOfAnEarlierRelease() {
        String oldValues = Arrays.stream(AuditAction.values())
                .filter(action -> action != AuditAction.ALERT_CONFIG_SAVE
                        && action != AuditAction.EXTERNAL_AUTH_SAVE)
                .map(Enum::name)
                .map(value -> "'" + value + "'")
                .collect(Collectors.joining(","));
        jdbcTemplate.execute("create table audit_event ("
                + "id bigint generated by default as identity, "
                + "occurred_at timestamp(6) not null, actor varchar(64) not null, "
                + "action enum(" + oldValues + ") not null, detail varchar(1024), "
                + "primary key (id))");
        jdbcTemplate.update("insert into audit_event (occurred_at, actor, action) "
                + "values (current_timestamp, 'someone', 'LOGIN')");
    }

    private String actionDataType() {
        return jdbcTemplate.queryForObject(
                "select DATA_TYPE from INFORMATION_SCHEMA.COLUMNS "
                        + "where TABLE_NAME = 'AUDIT_EVENT' and COLUMN_NAME = 'ACTION'",
                String.class);
    }

    private int insertNewAction() {
        return jdbcTemplate.update("insert into audit_event (occurred_at, actor, action, detail) "
                + "values (current_timestamp, 'someone', 'ALERT_CONFIG_SAVE', null)");
    }

    @Test
    void theColumnOfAnEarlierReleaseReallyRefusesTheNewConstant() {
        createSchemaOfAnEarlierRelease();

        assertThat(actionDataType()).isEqualTo("ENUM");
        assertThatCode(this::insertNewAction).isInstanceOf(RuntimeException.class);
    }

    @Test
    void theNewConstantBecomesInsertableAndTheOldRowsSurvive() {
        createSchemaOfAnEarlierRelease();

        migration.run(null);

        assertThat(actionDataType()).isEqualTo("CHARACTER VARYING");
        assertThat(insertNewAction()).isEqualTo(1);
        assertThat(jdbcTemplate.queryForObject("select count(*) from audit_event where action = 'LOGIN'",
                Integer.class)).isEqualTo(1);
    }

    @Test
    void aSecondBootOnTheWidenedColumnChangesNothing() {
        createSchemaOfAnEarlierRelease();
        migration.run(null);

        migration.run(null);

        assertThat(actionDataType()).isEqualTo("CHARACTER VARYING");
        assertThat(jdbcTemplate.queryForObject("select count(*) from audit_event", Integer.class))
                .isEqualTo(1);
    }

    /** A fresh database starts as a native enum too; the repair is the one that makes it text. */
    @Test
    void aColumnThatIsAlreadyTextIsLeftAlone() {
        jdbcTemplate.execute("create table audit_event ("
                + "id bigint generated by default as identity, "
                + "occurred_at timestamp(6) not null, actor varchar(64) not null, "
                + "action varchar(32) not null, detail varchar(1024), primary key (id))");

        migration.run(null);

        assertThat(actionDataType()).isEqualTo("CHARACTER VARYING");
    }

    /** An install whose metadata store predates the audit trail: booting must not fail. */
    @Test
    void anInstallWithoutTheTableBootsQuietly() {
        assertThatCode(() -> migration.run(null)).doesNotThrowAnyException();
    }

    /** The same repair on the other metadata databases Jync documents, each in its own dialect. */
    @Test
    void eachMetadataDatabaseGetsItsOwnStatement() {
        assertThat(AuditActionEnumMigration.h2Statement("ENUM"))
                .isEqualTo("ALTER TABLE audit_event ALTER COLUMN action SET DATA TYPE VARCHAR(32)");
        assertThat(AuditActionEnumMigration.h2Statement("CHARACTER VARYING")).isNull();

        assertThat(AuditActionEnumMigration.mysqlStatement("enum", false))
                .isEqualTo("ALTER TABLE audit_event MODIFY COLUMN action VARCHAR(32) NOT NULL");
        assertThat(AuditActionEnumMigration.mysqlStatement("varchar", false)).isNull();

        assertThat(AuditActionEnumMigration.postgresStatement("USER-DEFINED"))
                .isEqualTo("ALTER TABLE audit_event ALTER COLUMN action TYPE VARCHAR(32) "
                        + "USING action::text");
        assertThat(AuditActionEnumMigration.postgresStatement("character varying")).isNull();
    }
}
