package com.qqmu.jync.config;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatCode;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.lang.reflect.Field;
import java.util.LinkedHashSet;
import java.util.Locale;
import java.util.Set;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.config.BeanDefinition;
import org.springframework.context.annotation.ClassPathScanningCandidateComponentProvider;
import org.springframework.core.type.filter.AnnotationTypeFilter;
import org.springframework.dao.DataAccessException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Table;

/**
 * The metadata store of an earlier release pinned its enum columns to that release's constants:
 * a native ENUM on H2/MySQL, a varchar plus a CHECK constraint on PostgreSQL. Hibernate's
 * {@code ddl-auto=update} widens neither, so upgrading 2.3.0 → 2.4.1 used to crash at startup
 * when the local OPS account seeding queried {@code app_user.role = 'OPS'} (H2 error 22030;
 * PostgreSQL check-constraint violation) and the exception escaped the
 * {@code ApplicationReadyEvent} listener.
 *
 * <p>Entities now force text with {@code @JdbcTypeCode(SqlTypes.VARCHAR)}, so Hibernate's own
 * schema update converts a native ENUM. These tests drive the follow-up migration, which covers
 * what the schema update leaves behind — most importantly the value CHECK constraints Hibernate
 * writes on every store (a fresh install included) and never removes.
 */
class MetadataEnumColumnMigrationTest {

    private JdbcTemplate jdbcTemplate;
    private MetadataEnumColumnMigration migration;

    @BeforeEach
    void setUp() {
        // A private in-memory database per test: the migration alters a real schema, and H2
        // commits DDL immediately, so sharing one database would leak the change.
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:enum-migration-" + System.nanoTime() + ";MODE=MySQL;DB_CLOSE_DELAY=-1",
                "sa", "");
        jdbcTemplate = new JdbcTemplate(dataSource);
        migration = new MetadataEnumColumnMigration(jdbcTemplate);
    }

    /** The schema 2.3.0 leaves behind: USER_ROLE knew VIEWER and ADMIN only. */
    private void appUserOfAnEarlierRelease() {
        jdbcTemplate.execute("create table app_user ("
                + "id bigint generated by default as identity, "
                + "username varchar(64) not null, password_hash varchar(100) not null, "
                + "role enum('ADMIN', 'VIEWER') not null, primary key (id))");
        jdbcTemplate.update("insert into app_user (username, password_hash, role) "
                + "values ('admin', 'hash', 'ADMIN')");
    }

    private String dataType(String table, String column) {
        return jdbcTemplate.queryForObject(
                "select DATA_TYPE from INFORMATION_SCHEMA.COLUMNS "
                        + "where TABLE_NAME = ? and COLUMN_NAME = ?",
                String.class, table, column);
    }

    /**
     * The exact production failure: this is the query {@code AppUserService.seedIfEmpty}
     * runs on ApplicationReady, and its exception is what stopped the process.
     */
    @Test
    void theOperatorRoleOfAnEarlierReleaseRefusesTheUpgrade() {
        appUserOfAnEarlierRelease();

        assertThatThrownBy(() -> jdbcTemplate.queryForObject(
                "select count(*) from app_user where role = 'OPS'", Integer.class))
                .isInstanceOf(DataAccessException.class)
                .hasMessageContaining("OPS");
    }

    @Test
    void theUpgradedOperatorRoleBecomesUsableAndTheOldRowsSurvive() {
        appUserOfAnEarlierRelease();

        migration.run(null);

        assertThat(dataType("APP_USER", "ROLE")).isEqualTo("CHARACTER VARYING");
        assertThat(jdbcTemplate.update("insert into app_user (username, password_hash, role) "
                + "values ('ops', 'hash', 'OPS')")).isEqualTo(1);
        assertThat(jdbcTemplate.queryForObject(
                "select count(*) from app_user where role = 'ADMIN'", Integer.class)).isEqualTo(1);
    }

    /** 2.4.1's new connection type must be savable on a store created by 2.4.0 or earlier. */
    @Test
    void aNewConnectionTypeBecomesUsableOnAnEarlierStore() {
        jdbcTemplate.execute("create table database_config ("
                + "id bigint generated by default as identity, "
                + "name varchar(64) not null, "
                + "type enum('MYSQL', 'ORACLE', 'POSTGRESQL') not null, "
                + "primary key (id))");

        migration.run(null);

        assertThat(jdbcTemplate.update("insert into database_config (name, type) "
                + "values ('tdengine', 'TDENGINE')")).isEqualTo(1);
    }

    /** Every newer constant the pinned columns can receive is accepted after one boot. */
    @Test
    void newerConstantsOfTheOtherPinnedColumnsAreAcceptedToo() {
        jdbcTemplate.execute("create table audit_event ("
                + "id bigint generated by default as identity, "
                + "action enum('LOGIN', 'ALERT_SETTINGS_SAVE') not null, primary key (id))");
        jdbcTemplate.execute("create table etl_task ("
                + "id bigint generated by default as identity, "
                + "write_mode enum('OVERWRITE', 'APPEND') not null, primary key (id))");
        jdbcTemplate.execute("create table alert_state ("
                + "id bigint generated by default as identity, "
                + "category enum('SYNC_FAILURE', 'POLL_STUCK') not null, primary key (id))");
        jdbcTemplate.update("insert into audit_event (action) values ('LOGIN')");

        migration.run(null);

        assertThat(jdbcTemplate.update(
                "insert into audit_event (action) values ('AI_SUPPORT_ASK')")).isEqualTo(1);
        assertThat(jdbcTemplate.update("insert into etl_task (write_mode) values ('UPSERT')"))
                .isEqualTo(1);
        assertThat(jdbcTemplate.update(
                "insert into alert_state (category) values ('DDL_SKIPPED')")).isEqualTo(1);
        assertThat(jdbcTemplate.queryForObject(
                "select count(*) from audit_event", Integer.class)).isEqualTo(2);
    }

    /**
     * A fresh 2.4.2 install gets a text column but Hibernate still writes the constant set into
     * a CHECK constraint, so the next release's new role would be rejected on a store that was
     * never "upgraded" at all. This is the H2 shape Hibernate creates (auto-generated
     * constraint name, uppercase quoted column).
     */
    @Test
    void aFreshStoresHibernateCheckIsDroppedAsWell() {
        jdbcTemplate.execute("create table app_user ("
                + "id bigint generated by default as identity, "
                + "username varchar(64) not null, password_hash varchar(100) not null, "
                + "role varchar(16) not null check ((role in ('VIEWER','ADMIN'))), "
                + "primary key (id))");
        jdbcTemplate.update("insert into app_user (username, password_hash, role) "
                + "values ('admin', 'hash', 'ADMIN')");

        migration.run(null);

        assertThat(jdbcTemplate.update("insert into app_user (username, password_hash, role) "
                + "values ('ops', 'hash', 'OPS')")).isEqualTo(1);
        // The NOT NULL part of the definition must stay.
        assertThatThrownBy(() -> jdbcTemplate.update(
                "insert into app_user (username, password_hash, role) values ('x', 'hash', null)"))
                .isInstanceOf(DataAccessException.class);
    }

    @Test
    void aSecondBootOnTheWidenedColumnsChangesNothing() {
        appUserOfAnEarlierRelease();
        migration.run(null);

        migration.run(null);

        assertThat(dataType("APP_USER", "ROLE")).isEqualTo("CHARACTER VARYING");
        assertThat(jdbcTemplate.queryForObject("select count(*) from app_user", Integer.class))
                .isEqualTo(1);
    }

    /** An install whose metadata store predates some tables: booting must not fail. */
    @Test
    void anInstallWithoutTheTablesBootsQuietly() {
        assertThatCode(() -> migration.run(null)).doesNotThrowAnyException();
    }

    /** The same repair on the other metadata databases Jync documents, each in its dialect. */
    @Test
    void eachMetadataDatabaseGetsItsOwnStatement() {
        MetadataEnumColumnMigration.Column role =
                new MetadataEnumColumnMigration.Column("APP_USER", "ROLE");

        assertThat(MetadataEnumColumnMigration.h2Statement(role))
                .isEqualTo("ALTER TABLE app_user ALTER COLUMN role SET DATA TYPE VARCHAR(64)");
        assertThat(MetadataEnumColumnMigration.mysqlStatement(role, false))
                .isEqualTo("ALTER TABLE app_user MODIFY COLUMN role VARCHAR(64) NOT NULL");
        assertThat(MetadataEnumColumnMigration.mysqlStatement(role, true))
                .isEqualTo("ALTER TABLE app_user MODIFY COLUMN role VARCHAR(64) NULL");
        assertThat(MetadataEnumColumnMigration.postgresStatement(role))
                .isEqualTo("ALTER TABLE app_user ALTER COLUMN role TYPE VARCHAR(64) "
                        + "USING role::text");
        assertThat(MetadataEnumColumnMigration.postgresDropConstraintStatement(
                "app_user", "app_user_role_check"))
                .isEqualTo("ALTER TABLE app_user DROP CONSTRAINT IF EXISTS app_user_role_check");
        assertThat(MetadataEnumColumnMigration.oracleDropConstraintStatement(
                "APP_USER", "SYS_C008739"))
                .isEqualTo("ALTER TABLE APP_USER DROP CONSTRAINT SYS_C008739");
        assertThat(MetadataEnumColumnMigration.h2DropConstraintStatement(
                "app_user", "CONSTRAINT_7"))
                .isEqualTo("ALTER TABLE app_user DROP CONSTRAINT CONSTRAINT_7");
        assertThat(MetadataEnumColumnMigration.mysqlDropCheckStatement(
                "app_user", "app_user_chk_1"))
                .isEqualTo("ALTER TABLE app_user DROP CHECK app_user_chk_1");
        assertThat(MetadataEnumColumnMigration.mysqlDropConstraintStatement(
                "app_user", "app_user_chk_1"))
                .isEqualTo("ALTER TABLE app_user DROP CONSTRAINT app_user_chk_1");
    }

    /**
     * Oracle 23 stores the same frozen domain as varchar2 plus a CHECK, with a system-generated
     * constraint name. The definition therefore has to be recognized by shape — while the
     * NOT NULL constraints Oracle also reports as type C must be left alone.
     */
    @Test
    void oracleEnumCheckIsRecognizedButNotNullIsNot() {
        MetadataEnumColumnMigration.Column role =
                new MetadataEnumColumnMigration.Column("APP_USER", "ROLE");

        // The exact text Oracle 23 reports: the whole definition is wrapped in parentheses.
        assertThat(MetadataEnumColumnMigration.isStaleEnumCheck(
                role, "SYS_C008739", "(role in ('VIEWER','ADMIN'))")).isTrue();
        assertThat(MetadataEnumColumnMigration.isStaleEnumCheck(
                role, "SYS_C008739", " \"ROLE\" IN ('VIEWER','ADMIN', 'OPS')")).isTrue();
        assertThat(MetadataEnumColumnMigration.isStaleEnumCheck(
                role, "SYS_C008739", "((\"ROLE\" IN ('VIEWER','ADMIN')))")).isTrue();

        assertThat(MetadataEnumColumnMigration.isStaleEnumCheck(
                role, "SYS_C008735", "\"ID\" IS NOT NULL")).isFalse();
        assertThat(MetadataEnumColumnMigration.isStaleEnumCheck(
                role, "SYS_C008738", "username in ('a','b')")).isFalse();

        // H2 names a fresh store's check CONSTRAINT_N and quotes the column; MySQL names it
        // <table>_chk_N and backquotes; SQL Server brackets. All are the same frozen domain.
        assertThat(MetadataEnumColumnMigration.isStaleEnumCheck(
                role, "CONSTRAINT_7", "\"ROLE\" IN('VIEWER', 'ADMIN')")).isTrue();
        assertThat(MetadataEnumColumnMigration.isStaleEnumCheck(
                role, "app_user_chk_1", "(`role` in (_utf8mb4'VIEWER',_utf8mb4'ADMIN'))")).isTrue();
        assertThat(MetadataEnumColumnMigration.isStaleEnumCheck(
                role, "CK_app_user_role", "[role] in ('VIEWER','ADMIN')")).isTrue();
        assertThat(MetadataEnumColumnMigration.isOracle("Oracle")).isTrue();
        assertThat(MetadataEnumColumnMigration.isOracle("Oracle Database 23ai")).isTrue();
        assertThat(MetadataEnumColumnMigration.isOracle("PostgreSQL")).isFalse();
    }

    /**
     * PostgreSQL freezes the constants in a CHECK constraint. The real definition PostgreSQL
     * reports for the 2.2.1 store is used here; an unrelated constraint on the same column, and
     * another column's enum CHECK, must both be left alone.
     */
    @Test
    void onlyTheStaleEnumCheckOfThePinnedColumnIsRecognized() {
        MetadataEnumColumnMigration.Column role =
                new MetadataEnumColumnMigration.Column("APP_USER", "ROLE");
        String legacy = "CHECK (((role)::text = ANY ((ARRAY['VIEWER'::character varying, "
                + "'ADMIN'::character varying])::text[])))";

        assertThat(MetadataEnumColumnMigration.isStaleEnumCheck(
                role, "app_user_role_check", legacy)).isTrue();
        // A store whose constraint was named differently is still recognized by its shape.
        assertThat(MetadataEnumColumnMigration.isStaleEnumCheck(
                role, "ck_app_user_role", legacy)).isTrue();
        // Hibernate 5/6 wrote the same domain as an IN list.
        assertThat(MetadataEnumColumnMigration.isStaleEnumCheck(
                role, "some_name", "CHECK (((role) IN ('ADMIN'::character varying, "
                        + "'VIEWER'::character varying)))")).isTrue();

        assertThat(MetadataEnumColumnMigration.isStaleEnumCheck(
                role, "app_user_username_check",
                "CHECK (((username)::text = ANY ((ARRAY['a'::character varying])::text[])))"))
                .isFalse();
        assertThat(MetadataEnumColumnMigration.isStaleEnumCheck(
                role, "app_user_port_check", "CHECK ((port > 0))")).isFalse();
        assertThat(MetadataEnumColumnMigration.isStaleEnumCheck(role, null, null)).isFalse();
    }

    /**
     * The pinned list is what protects an upgrade; a new enum column added to an entity
     * without a line here would keep an old constant set instead of being migrated.
     */
    @Test
    void everyEnumColumnTheEntitiesDeclareIsPinned() throws ClassNotFoundException {
        Set<String> declared = new LinkedHashSet<>();
        ClassPathScanningCandidateComponentProvider scanner =
                new ClassPathScanningCandidateComponentProvider(false);
        scanner.addIncludeFilter(new AnnotationTypeFilter(Entity.class));
        for (BeanDefinition definition : scanner.findCandidateComponents("com.qqmu.jync.model")) {
            Class<?> entity = Class.forName(definition.getBeanClassName());
            Table table = entity.getAnnotation(Table.class);
            String tableName = table != null && !table.name().isEmpty()
                    ? table.name() : snake(entity.getSimpleName());
            for (Field field : entity.getDeclaredFields()) {
                Enumerated enumerated = field.getAnnotation(Enumerated.class);
                if (enumerated == null || enumerated.value() != EnumType.STRING) {
                    continue;
                }
                jakarta.persistence.Column column =
                        field.getAnnotation(jakarta.persistence.Column.class);
                String columnName = column != null && !column.name().isEmpty()
                        ? column.name() : snake(field.getName());
                declared.add(tableName + "." + columnName);
            }
        }

        Set<String> pinned = new LinkedHashSet<>();
        for (MetadataEnumColumnMigration.Column column : MetadataEnumColumnMigration.COLUMNS) {
            pinned.add(column.table() + "." + column.column());
        }

        assertThat(pinned).containsExactlyInAnyOrderElementsOf(declared);
    }

    private static String snake(String camelCase) {
        StringBuilder out = new StringBuilder();
        for (char c : camelCase.toCharArray()) {
            if (Character.isUpperCase(c) && out.length() > 0) {
                out.append('_');
            }
            out.append(Character.toLowerCase(c));
        }
        return out.toString().toLowerCase(Locale.ROOT);
    }
}
