package com.qqmu.jync.util;

import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

import com.qqmu.jync.dto.meta.ColumnMeta;
import com.qqmu.jync.dto.meta.TableMeta;
import com.qqmu.jync.model.DatabaseType;
import com.qqmu.jync.service.converter.VendorTypeMap;

/**
 * Checks that an already-existing target table can actually receive the source's rows.
 *
 * <p>This guards the case "table of the right name but the wrong shape" — a manually pre-created
 * table missing a column, or created with stale types before structure sync ever ran. Without a
 * check, data sync fails row-by-row with cryptic driver errors, or worse silently truncates
 * values on a permissive target. The check is deliberately loose: columns must exist and belong
 * to the same broad type family (strings accept strings, numbers accept numbers), since the
 * alternatives (refusing a safe {@code INT→BIGINT}) would block perfectly good deployments.
 */
public final class TargetTableVerifier {

    private TargetTableVerifier() {
    }

    /**
     * @return null when the target is compatible, otherwise a human-readable reason naming the
     *     first column that makes it unusable
     */
    public static String verify(Connection conn, String schema, String tableName,
                                TableMeta sourceTable) throws SQLException {
        return verify(conn, schema, tableName, sourceTable, null);
    }

    /**
     * Type-aware variant. For Oracle-family targets (Oracle, 达梦, 崖山) the metadata lookup
     * folds schema/table names to upper case — unquoted identifiers are stored that way, so a
     * raw lower-case pattern simply finds nothing — and a pre-existing
     * {@code GENERATED ALWAYS AS IDENTITY} column is rejected up front: data sync writes source
     * id values explicitly, which such a column refuses (ORA-32795) row by row.
     */
    public static String verify(Connection conn, String schema, String tableName,
                                TableMeta sourceTable, DatabaseType targetType) throws SQLException {
        boolean oracleFamily = isOracleFamily(targetType);
        String lookupSchema = foldIfOracle(oracleFamily, normalizeSchema(schema));
        String lookupTable = foldIfOracle(oracleFamily, tableName);
        Map<String, TargetColumn> targetTypes = readTargetColumns(conn, lookupSchema, lookupTable);

        for (ColumnMeta sourceColumn : sourceTable.getColumns()) {
            TargetColumn found = targetTypes.get(sourceColumn.getName().toUpperCase(Locale.ROOT));
            if (found == null) {
                return "target table " + lookupTable + " is missing column " + sourceColumn.getName()
                        + " (a table with this name exists but its shape does not match the"
                        + " source). Turn structure sync on so Jync adds the missing column,"
                        + " or add it yourself.";
            }
            if (sourceFamily(sourceColumn) != targetFamily(found, targetType)) {
                return "target table " + lookupTable + " column " + sourceColumn.getName()
                        + " has an incompatible type (source JDBC type " + sourceColumn.getJdbcType()
                        + " vs target " + found.jdbcType() + "). Align the column types.";
            }
        }

        if (oracleFamily) {
            String alwaysColumn = findAlwaysIdentityColumn(conn, lookupSchema, lookupTable,
                    sourceTable);
            if (alwaysColumn != null) {
                return "target table " + lookupTable + " column " + alwaysColumn
                        + " is GENERATED ALWAYS AS IDENTITY and rejects inserted id values"
                        + " (ORA-32795), but this sync writes the source id explicitly. Recreate"
                        + " the target column as GENERATED BY DEFAULT ON NULL AS IDENTITY, or drop"
                        + " the table so structure sync recreates it.";
            }
        }
        return null;
    }

    /**
     * Source columns the target table does not have, in source order.
     *
     * <p>This is the additive half of a shape mismatch, reported separately because it is the
     * only half that can be repaired mechanically: a missing column is added without touching a
     * single existing row, while a wrong type or a bad identity clause needs a human decision.
     * The caller therefore adds these before deciding the table is unusable.
     */
    public static List<ColumnMeta> missingColumns(Connection conn, String schema, String tableName,
                                                  TableMeta sourceTable) throws SQLException {
        return missingColumns(conn, schema, tableName, sourceTable, null);
    }

    /** Type-aware variant, folding Oracle-family identifiers the same way {@link #verify} does. */
    public static List<ColumnMeta> missingColumns(Connection conn, String schema, String tableName,
                                                  TableMeta sourceTable, DatabaseType targetType)
            throws SQLException {
        boolean oracleFamily = isOracleFamily(targetType);
        Map<String, TargetColumn> targetTypes = readTargetColumns(conn,
                foldIfOracle(oracleFamily, normalizeSchema(schema)),
                foldIfOracle(oracleFamily, tableName));
        List<ColumnMeta> missing = new ArrayList<>();
        for (ColumnMeta sourceColumn : sourceTable.getColumns()) {
            if (!targetTypes.containsKey(sourceColumn.getName().toUpperCase(Locale.ROOT))) {
                missing.add(sourceColumn);
            }
        }
        return missing;
    }

    /**
     * The requested columns whose TARGET column values cannot be compared with {@code =} and
     * {@code <>}, in the order asked for. An empty result vouches for all of them.
     *
     * <p>This is what lets a dialect add a "something really differs" condition to its upsert
     * (see {@link com.qqmu.jync.service.converter.SqlDialect#getUpsertSql(String, String, List,
     * List, java.util.Map, boolean)}): such a condition is only sound when every non-key column
     * can be compared, because comparing a CLOB fails the whole statement on Oracle
     * (ORA-22848/ORA-00932) and because guarding a subset would silently skip rows whose only
     * change is in the column left out.
     *
     * <p>The check reads the target's own dictionary rather than the bind types the caller also
     * has: those describe the source's values, and a VARCHAR source landing in a CLOB target is
     * a shape this sync supports ({@link #verify} accepts it deliberately). Anything that
     * cannot be positively confirmed — an unknown type, a column the target does not have — is
     * reported as not comparable, since the cost of being wrong that way is an extra change-log
     * line, while the cost of the opposite is a sync that fails on every row.
     */
    public static List<String> uncomparableColumns(Connection conn, String schema, String tableName,
                                                   DatabaseType targetType, List<String> columns)
            throws SQLException {
        if (columns == null || columns.isEmpty()) {
            return List.of();
        }
        boolean oracleFamily = isOracleFamily(targetType);
        Map<String, TargetColumn> targetTypes = readTargetColumns(conn,
                foldIfOracle(oracleFamily, normalizeSchema(schema)),
                foldIfOracle(oracleFamily, tableName));
        List<String> uncomparable = new ArrayList<>();
        for (String column : columns) {
            TargetColumn found = column == null ? null
                    : targetTypes.get(column.toUpperCase(Locale.ROOT));
            if (found == null || !supportsEquality(found)) {
                uncomparable.add(column);
            }
        }
        return uncomparable;
    }

    /**
     * Whether {@code =} and {@code <>} are defined for a column of this JDBC type. A whitelist,
     * not a list of exclusions: everything outside it is either a type whose comparison fails
     * (CLOB, BLOB, LONG, SQLXML, and PostgreSQL's {@code json}, which has no equality operator)
     * or a vendor type this code cannot classify, and in both cases standing down is the safe
     * answer.
     */
    static boolean supportsEquality(TargetColumn column) {
        if (VendorTypeMap.isNonComparableName(column.typeName())) {
            return false;
        }
        switch (column.jdbcType()) {
            case java.sql.Types.CHAR:
            case java.sql.Types.VARCHAR:
            case java.sql.Types.NCHAR:
            case java.sql.Types.NVARCHAR:
            case java.sql.Types.TINYINT:
            case java.sql.Types.SMALLINT:
            case java.sql.Types.INTEGER:
            case java.sql.Types.BIGINT:
            case java.sql.Types.FLOAT:
            case java.sql.Types.REAL:
            case java.sql.Types.DOUBLE:
            case java.sql.Types.NUMERIC:
            case java.sql.Types.DECIMAL:
            case java.sql.Types.DATE:
            case java.sql.Types.TIME:
            case java.sql.Types.TIME_WITH_TIMEZONE:
            case java.sql.Types.TIMESTAMP:
            case java.sql.Types.TIMESTAMP_WITH_TIMEZONE:
            case java.sql.Types.BINARY:
            case java.sql.Types.VARBINARY:
            case java.sql.Types.BOOLEAN:
            case java.sql.Types.BIT:
                return true;
            default:
                return false;
        }
    }

    private static boolean isOracleFamily(DatabaseType targetType) {
        return targetType != null
                && targetType.getFamily() == DatabaseType.DialectFamily.ORACLE;
    }

    /** A blank schema means "the connection's own schema", the same thing null means. */
    private static String normalizeSchema(String schema) {
        return schema == null || schema.isBlank() ? null : schema;
    }

    /** Oracle stores unquoted identifiers upper-cased, so a raw lower-case pattern finds nothing. */
    private static String foldIfOracle(boolean oracleFamily, String name) {
        return oracleFamily && name != null ? name.toUpperCase(Locale.ROOT) : name;
    }

    /** Column name (upper-cased) to JDBC type of the target table. Empty when it is absent. */
    private static Map<String, TargetColumn> readTargetColumns(Connection conn, String schema,
                                                               String tableName)
            throws SQLException {
        DatabaseMetaData metaData = conn.getMetaData();
        Map<String, TargetColumn> columns = new LinkedHashMap<>();
        // Catalog stays null: MySQL uses the current database, others key on schema/owner.
        try (ResultSet rs = metaData.getColumns(null, schema, tableName, "%")) {
            while (rs.next()) {
                columns.put(rs.getString("COLUMN_NAME").toUpperCase(Locale.ROOT),
                        new TargetColumn(rs.getInt("DATA_TYPE"), rs.getInt("COLUMN_SIZE"),
                                rs.getString("TYPE_NAME")));
            }
        }
        return columns;
    }

    /**
     * Name of a source-autoincrement column that is GENERATED ALWAYS on the target, or null.
     * Returns null on servers without {@code ALL_TAB_IDENTITY_COLS} (11g, look-alikes).
     */
    private static String findAlwaysIdentityColumn(Connection conn, String schema, String tableName,
                                                   TableMeta sourceTable) {
        String sql = "SELECT COLUMN_NAME FROM ALL_TAB_IDENTITY_COLS "
                + "WHERE OWNER = NVL(?, USER) AND TABLE_NAME = ? AND GENERATION_TYPE = 'ALWAYS'";
        try (java.sql.PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, schema);
            ps.setString(2, tableName);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    String targetColumn = rs.getString(1);
                    if (targetColumn == null) {
                        continue;
                    }
                    for (ColumnMeta sourceColumn : sourceTable.getColumns()) {
                        if (sourceColumn.isAutoIncrement() && sourceColumn.getName() != null
                                && sourceColumn.getName().toUpperCase(Locale.ROOT)
                                        .equals(targetColumn.toUpperCase(Locale.ROOT))) {
                            return targetColumn.toUpperCase(Locale.ROOT);
                        }
                    }
                }
            }
        } catch (SQLException e) {
            // View absent (11g) or not exposed by a look-alike: nothing to pre-check.
        }
        return null;
    }

    /**
     * Broad family of the values a SOURCE column actually carries. This diverges from the
     * raw JDBC type in one case: MySQL-family drivers report YEAR as JDBC DATE, but the
     * values are integer years, so it belongs with numerics (and must not match a DATE
     * target, which could not receive the integer bind).
     */
    private static int sourceFamily(ColumnMeta column) {
        if (column.getJdbcType() == java.sql.Types.DATE
                && column.getTypeName() != null
                && "YEAR".equalsIgnoreCase(column.getTypeName().trim())) {
            return 2;
        }
        // BIT(1) is a boolean, but a multi-bit BIT (MySQL's BIT(n>1)) carries an unsigned
        // integer as a byte array and maps onto integer targets. SQL Server's boolean BIT
        // always reports width 1, so a width above 1 unambiguously means the integer case.
        if (column.getJdbcType() == java.sql.Types.BIT
                && column.getSize() != null
                && column.getSize() > 1) {
            return 2;
        }
        // F-9: PG reports JSON/JSONB/UUID/XML as JDBC OTHER (1111), but their values are
        // read and written as text (JdbcRowMapper renders them via getString), so they
        // belong with strings — a pre-created TEXT/VARCHAR target is the recommended
        // 信创 landing shape. Other OTHER types (geometric point, …) stay exact-match.
        if (column.getJdbcType() == java.sql.Types.OTHER
                && isTextBorneOther(column.getTypeName())) {
            return 1;
        }
        return VendorTypeMap.family(null, column.getJdbcType(), column.getTypeName());
    }

    /** The target column's dictionary entry: JDBC type, declared width and type name. */
    private record TargetColumn(int jdbcType, int columnSize, String typeName) {
    }

    /**
     * Family of the TARGET column's reported JDBC type, judged the same way the source side
     * judges it. Two divergences from the raw table:
     *
     * <p>Oracle's driver reports its native floating types with vendor codes that are not in
     * {@link java.sql.Types}, so the generic table would file them under "unknown — must match
     * exactly". They are plain numbers, and {@link com.qqmu.jync.service.converter.OracleDialect}
     * creates exactly these two for a source FLOAT/DOUBLE — without this the verifier rejected
     * the table the generator had just built ("source JDBC type 8 vs target 101") and the sync
     * stopped on its own DDL.
     *
     * <p>MySQL reports both {@code BIT(1)} and {@code BIT(n)} as JDBC BIT, so the width decides
     * the family — the same rule {@link #sourceFamily} applies (see there). Reading the width
     * from the dictionary is what makes a MySQL {@code BIT(16)} → {@code BIT(16)} pair pass:
     * both sides report JDBC type -7, and a family that ignored the width called the source's
     * own shape incompatible and aborted the baseline.
     */
    private static int targetFamily(TargetColumn column, DatabaseType targetType) {
        int jdbcType = column.jdbcType();
        if (jdbcType == java.sql.Types.BIT && column.columnSize() > 1) {
            return 2; // MySQL BIT(n>1) holds an unsigned integer, as on the source side
        }
        return VendorTypeMap.family(targetType, jdbcType, column.typeName());
    }

    private static boolean isTextBorneOther(String typeName) {
        if (typeName == null) {
            return false;
        }
        String n = typeName.trim().toLowerCase(Locale.ROOT);
        return n.equals("json") || n.equals("jsonb") || n.equals("uuid")
                || n.equals("xml");
    }

}
