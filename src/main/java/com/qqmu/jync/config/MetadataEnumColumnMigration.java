package com.qqmu.jync.config;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.regex.Pattern;

import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.core.Ordered;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.ConnectionCallback;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

import lombok.extern.slf4j.Slf4j;

/**
 * Removes the old constant sets that an earlier release pinned onto the metadata store's enum
 * columns, so an upgrade can save constants introduced later.
 *
 * <p>Hibernate 7 used to map {@code @Enumerated(EnumType.STRING)} to a database type frozen at
 * the constants of the release that created it: a native ENUM on H2/MySQL, a varchar plus a
 * CHECK constraint on PostgreSQL and Oracle. {@code ddl-auto=update} compares only the type
 * name, so neither form is widened when a later release adds a constant. Upgrading 2.3.0 → 2.4.1
 * hit exactly that: the local OPS account seeding queries {@code app_user.role = 'OPS'} from an
 * {@code ApplicationReadyEvent} listener, the store rejects it (H2 error 22030, PostgreSQL and
 * Oracle check-constraint violations), the exception escapes the listener, and the process
 * exits before the first request. The same trap rejected 2.4.1's TDENGINE connection type in
 * {@code database_config.type}, the newer ETL write modes and the newer alert categories.
 *
 * <p>Entities now declare {@code @JdbcTypeCode(SqlTypes.VARCHAR)} next to
 * {@code @Enumerated(STRING)}, so Hibernate expects text and its own schema update converts a
 * native ENUM as soon as the new release boots (see {@code EnumColumnsStoredAsTextTest}). That
 * alone is not enough: on a fresh table Hibernate still writes the constant set into a CHECK
 * constraint, and on an existing store those constraints survive {@code ddl-auto=update}. This
 * runner covers both: it is the safety net for a store whose enum columns Hibernate left alone,
 * and it drops the stale value CHECK on H2, MySQL, PostgreSQL and Oracle, whose names are
 * generated by Hibernate or by the database and whose definitions are the only reliable
 * selector. It runs after the schema update and before the application-ready seeding, so the
 * seeding already sees the widened domain.
 *
 * <p>Only the columns pinned in {@link #COLUMNS} are touched; another application's schema is
 * never altered. A failure is logged, not rethrown, and one column's failure does not stop the
 * others: booting with one narrow column is still better than not booting, and the operator
 * sees the statement to run by hand.
 */
@Component
@Order(Ordered.HIGHEST_PRECEDENCE)
@Slf4j
public class MetadataEnumColumnMigration implements ApplicationRunner {

    static final String TEXT = "VARCHAR(64)";

    /**
     * Every enum column Jync's entities declare ({@code @Enumerated(EnumType.STRING)}).
     * {@link MetadataEnumColumnMigrationTest} scans the entities and fails if this list drifts:
     * a new enum column that is not pinned here would keep the constant set of the release whose
     * store it was created on instead of being widened by this runner.
     */
    static final List<Column> COLUMNS = List.of(
            new Column("ai_provider", "protocol"),
            new Column("ai_provider", "reasoning_effort"),
            new Column("alert_config", "webhook_format"),
            new Column("alert_state", "category"),
            new Column("app_user", "role"),
            new Column("audit_event", "action"),
            new Column("change_log", "change_type"),
            new Column("change_log", "object_type"),
            new Column("database_config", "dialect_family"),
            new Column("database_config", "role"),
            new Column("database_config", "type"),
            new Column("etl_task", "write_mode"),
            new Column("metadata_snapshot", "object_type"),
            new Column("migration_connection", "auth_type"),
            new Column("migration_connection", "kind"),
            new Column("migration_run", "status"),
            new Column("migration_run", "trigger_type"),
            new Column("migration_task", "type"),
            new Column("oa_auth_config", "auth_mode"),
            new Column("oa_auth_config", "request_format"),
            new Column("oa_auth_config", "validate_method"),
            new Column("project", "target_kind"),
            new Column("sync_progress", "object_type"),
            new Column("sync_task", "status"));

    private static final String H2_ENUMS =
            "select TABLE_NAME, COLUMN_NAME from INFORMATION_SCHEMA.COLUMNS "
            + "where TABLE_SCHEMA = SCHEMA() and DATA_TYPE = 'ENUM'";

    /**
     * Hibernate also pins the constant set on a fresh table, as a CHECK whose name it lets the
     * database generate ({@code CONSTRAINT_N} on H2, {@code <table>_chk_N} on MySQL), so the
     * definition is the only reliable selector there.
     */
    private static final String H2_CHECKS =
            "select tc.TABLE_NAME, tc.CONSTRAINT_NAME, cc.CHECK_CLAUSE "
            + "from INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc "
            + "join INFORMATION_SCHEMA.CHECK_CONSTRAINTS cc "
            + "on cc.CONSTRAINT_SCHEMA = tc.CONSTRAINT_SCHEMA "
            + "and cc.CONSTRAINT_NAME = tc.CONSTRAINT_NAME "
            + "where tc.CONSTRAINT_TYPE = 'CHECK' and tc.CONSTRAINT_SCHEMA = SCHEMA()";

    private static final String MYSQL_ENUMS =
            "select TABLE_NAME, COLUMN_NAME, IS_NULLABLE from information_schema.COLUMNS "
            + "where TABLE_SCHEMA = DATABASE() and DATA_TYPE = 'enum'";

    private static final String MYSQL_CHECKS =
            "select tc.TABLE_NAME, tc.CONSTRAINT_NAME, cc.CHECK_CLAUSE "
            + "from information_schema.TABLE_CONSTRAINTS tc "
            + "join information_schema.CHECK_CONSTRAINTS cc "
            + "on cc.CONSTRAINT_SCHEMA = tc.CONSTRAINT_SCHEMA "
            + "and cc.CONSTRAINT_NAME = tc.CONSTRAINT_NAME "
            + "where tc.CONSTRAINT_SCHEMA = DATABASE() and tc.CONSTRAINT_TYPE = 'CHECK'";

    private static final String POSTGRES_COLUMNS =
            "select table_name, column_name, data_type from information_schema.columns "
            + "where table_schema = current_schema()";

    /** CHECK constraints of the current schema, with their table and definition. */
    private static final String POSTGRES_CHECKS =
            "select t.relname, c.conname, pg_get_constraintdef(c.oid) "
            + "from pg_constraint c "
            + "join pg_class t on t.oid = c.conrelid "
            + "join pg_namespace n on n.oid = t.relnamespace "
            + "where c.contype = 'c' and n.nspname = current_schema()";

    /**
     * Oracle reports the enum CHECK and its own NOT NULL enforcement both as type C; the
     * definition decides which is which.
     */
    private static final String ORACLE_CHECKS =
            "select table_name, constraint_name, search_condition_vc from user_constraints "
            + "where constraint_type = 'C' and search_condition_vc is not null";

    private final JdbcTemplate jdbcTemplate;

    public MetadataEnumColumnMigration(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    /** One metadata column; names are normalized so catalog case never matters. */
    record Column(String table, String column) {
        Column {
            table = table.toLowerCase(Locale.ROOT);
            column = column.toLowerCase(Locale.ROOT);
        }
    }

    @Override
    public void run(ApplicationArguments args) {
        try {
            String product = jdbcTemplate.execute(
                    (ConnectionCallback<String>) connection ->
                            connection.getMetaData().getDatabaseProductName());
            if (isH2(product)) {
                widenH2();
                dropH2EnumChecks();
            } else if (isMySqlFamily(product)) {
                widenMySql();
                dropMySqlEnumChecks(product);
            } else if (isPostgres(product)) {
                widenPostgres();
                dropPostgresEnumChecks();
            } else if (isOracle(product)) {
                dropOracleEnumChecks();
            }
        } catch (RuntimeException e) {
            log.warn("Could not inspect the metadata enum columns; saving newer enum constants "
                    + "may fail until they are widened by hand: {}", e.getMessage());
        }
    }

    private void widenH2() {
        Set<Column> nativeEnums = new HashSet<>(jdbcTemplate.query(H2_ENUMS,
                (rs, rowNum) -> new Column(rs.getString(1), rs.getString(2))));
        for (Column column : COLUMNS) {
            if (nativeEnums.contains(column)) {
                execute(column, h2Statement(column));
            }
        }
    }

    private void widenMySql() {
        Map<Column, Boolean> nullable = new HashMap<>();
        jdbcTemplate.query(MYSQL_ENUMS, rs -> {
            nullable.put(new Column(rs.getString(1), rs.getString(2)),
                    "YES".equalsIgnoreCase(rs.getString(3)));
        });
        for (Column column : COLUMNS) {
            Boolean isNullable = nullable.get(column);
            if (isNullable != null) {
                execute(column, mysqlStatement(column, isNullable));
            }
        }
    }

    private void widenPostgres() {
        Set<Column> nativeEnums = new HashSet<>();
        jdbcTemplate.query(POSTGRES_COLUMNS, rs -> {
            if ("USER-DEFINED".equalsIgnoreCase(rs.getString(3))) {
                nativeEnums.add(new Column(rs.getString(1), rs.getString(2)));
            }
        });
        for (Column column : COLUMNS) {
            if (nativeEnums.contains(column)) {
                execute(column, postgresStatement(column));
            }
        }
    }

    /**
     * H2 names the check Hibernate writes on a fresh table {@code CONSTRAINT_N}; only the
     * definition identifies it.
     */
    private void dropH2EnumChecks() {
        dropStaleChecks(staleChecks(H2_CHECKS),
                MetadataEnumColumnMigration::h2DropConstraintStatement);
    }

    /**
     * MySQL names the check {@code <table>_chk_N}. {@code DROP CHECK} needs MySQL 8.0.16+;
     * MariaDB has no such clause and takes {@code DROP CONSTRAINT} instead.
     */
    private void dropMySqlEnumChecks(String product) {
        boolean mariaDb = product != null
                && product.toLowerCase(Locale.ROOT).contains("mariadb");
        dropStaleChecks(staleChecks(MYSQL_CHECKS), mariaDb
                ? MetadataEnumColumnMigration::mysqlDropConstraintStatement
                : MetadataEnumColumnMigration::mysqlDropCheckStatement);
    }

    /**
     * PostgreSQL stores {@code @Enumerated(STRING)} as varchar plus a CHECK listing the constants
     * at creation time, and Hibernate's schema update never removes that CHECK. The column itself
     * is already text, so only the stale constraint stands between an upgrade and the new
     * constants. Constraints are collected first and dropped after the query, so no DDL runs
     * while a result set holds a pooled connection.
     */
    private void dropPostgresEnumChecks() {
        dropStaleChecks(staleChecks(POSTGRES_CHECKS),
                MetadataEnumColumnMigration::postgresDropConstraintStatement);
    }

    /**
     * Oracle 23 (and the dialect's fallback for older versions) stores the same frozen domain
     * as varchar2 plus a CHECK named {@code SYS_Cxxxxx}, so the definition is the only way to
     * tell it apart from the NOT NULL constraints Oracle also reports as type C.
     */
    private void dropOracleEnumChecks() {
        dropStaleChecks(staleChecks(ORACLE_CHECKS),
                MetadataEnumColumnMigration::oracleDropConstraintStatement);
    }

    private List<CheckConstraint> staleChecks(String query) {
        List<CheckConstraint> stale = new ArrayList<>();
        jdbcTemplate.query(query, rs -> {
            String table = rs.getString(1);
            String name = rs.getString(2);
            String definition = rs.getString(3);
            for (Column column : COLUMNS) {
                if (column.table().equalsIgnoreCase(table)
                        && isStaleEnumCheck(column, name, definition)) {
                    stale.add(new CheckConstraint(column, table, name));
                }
            }
        });
        return stale;
    }

    private void dropStaleChecks(List<CheckConstraint> stale,
            java.util.function.BiFunction<String, String, String> statementFor) {
        for (CheckConstraint check : stale) {
            String statement = statementFor.apply(check.table(), check.name());
            try {
                jdbcTemplate.execute(statement);
                log.info("Dropped enum check constraint {} on metadata column {}.{}",
                        check.name(), check.column().table(), check.column().column());
            } catch (RuntimeException e) {
                log.warn("Could not drop the outdated enum check constraint {} on metadata "
                        + "column {}.{}; saving newer enum constants may fail until it is "
                        + "dropped by hand ({}): {}", check.name(), check.column().table(),
                        check.column().column(), statement, e.getMessage());
            }
        }
    }

    private void execute(Column column, String statement) {
        try {
            jdbcTemplate.execute(statement);
            log.info("Converted metadata column {}.{} to {}", column.table(), column.column(),
                    TEXT);
        } catch (RuntimeException e) {
            log.warn("Could not convert metadata column {}.{} to {}; saving newer enum constants"
                    + " may fail until it is converted by hand ({}): {}", column.table(),
                    column.column(), TEXT, statement, e.getMessage());
        }
    }

    /**
     * True when a CHECK constraint is Hibernate's frozen enum domain for this column: named
     * {@code <table>_<column>_check} (Hibernate's naming, both in the native-ENUM era and the
     * varchar era) or shaped as an enumeration of the column's allowed values.
     */
    static boolean isStaleEnumCheck(Column column, String name, String definition) {
        if (name != null
                && name.equalsIgnoreCase(column.table() + "_" + column.column() + "_check")) {
            return true;
        }
        if (definition == null) {
            return false;
        }
        // PostgreSQL keeps its ARRAY[...] literal, so brackets are stripped only for the IN-list
        // shape (SQL Server writes column names in them).
        String normalized = definition.replace("\"", "").replace("`", "").trim()
                .toLowerCase(Locale.ROOT);
        String col = column.column();
        // PostgreSQL wraps the array in extra parentheses ("ANY ((ARRAY[..."), so check the
        // pieces rather than one exact shape. Both PostgreSQL (Hibernate 5/6) and Oracle write
        // an IN list, either as "role in (...)" or "(role) in (...)"; Oracle also wraps the
        // whole definition in parentheses, which is why the column is matched by boundary
        // rather than by position.
        boolean inList = Pattern.compile("(?<![a-z0-9_])" + Pattern.quote(col)
                        + "\\)?\\s+in\\s*\\(")
                .matcher(normalized.replace("[", "").replace("]", ""))
                .find();
        return (normalized.contains("(" + col + ")::text")
                        && normalized.contains("= any")
                        && normalized.contains("array["))
                || inList;
    }

    /** Table and column come from {@link #COLUMNS}, never from user input. */
    static String h2Statement(Column column) {
        return "ALTER TABLE " + column.table() + " ALTER COLUMN " + column.column()
                + " SET DATA TYPE " + TEXT;
    }

    static String mysqlStatement(Column column, boolean nullable) {
        return "ALTER TABLE " + column.table() + " MODIFY COLUMN " + column.column() + " "
                + TEXT + (nullable ? " NULL" : " NOT NULL");
    }

    static String postgresStatement(Column column) {
        return "ALTER TABLE " + column.table() + " ALTER COLUMN " + column.column()
                + " TYPE " + TEXT + " USING " + column.column() + "::text";
    }

    static String postgresDropConstraintStatement(String table, String constraint) {
        return "ALTER TABLE " + table + " DROP CONSTRAINT IF EXISTS " + constraint;
    }

    static String oracleDropConstraintStatement(String table, String constraint) {
        return "ALTER TABLE " + table + " DROP CONSTRAINT " + constraint;
    }

    static String h2DropConstraintStatement(String table, String constraint) {
        return "ALTER TABLE " + table + " DROP CONSTRAINT " + constraint;
    }

    static String mysqlDropCheckStatement(String table, String constraint) {
        return "ALTER TABLE " + table + " DROP CHECK " + constraint;
    }

    static String mysqlDropConstraintStatement(String table, String constraint) {
        return "ALTER TABLE " + table + " DROP CONSTRAINT " + constraint;
    }

    static boolean isH2(String productName) {
        return productName != null && productName.toLowerCase(Locale.ROOT).contains("h2");
    }

    static boolean isMySqlFamily(String productName) {
        if (productName == null) {
            return false;
        }
        String normalized = productName.toLowerCase(Locale.ROOT);
        return normalized.contains("mysql") || normalized.contains("mariadb");
    }

    static boolean isPostgres(String productName) {
        return productName != null && productName.toLowerCase(Locale.ROOT).contains("postgresql");
    }

    static boolean isOracle(String productName) {
        return productName != null && productName.toLowerCase(Locale.ROOT).contains("oracle");
    }

    private record CheckConstraint(Column column, String table, String name) {
    }
}
