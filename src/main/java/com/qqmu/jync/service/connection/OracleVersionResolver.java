package com.qqmu.jync.service.connection;

import java.sql.CallableStatement;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Types;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import org.springframework.stereotype.Component;

import lombok.extern.slf4j.Slf4j;

/**
 * Resolves an Oracle-family target's effective major version for version-sensitive SQL.
 *
 * <p>"Effective" is the lower of two facts: the product release and the database's
 * {@code COMPATIBLE} parameter. A 19c database left at {@code compatible=11.2} still rejects
 * 12c-only syntax such as {@code AS IDENTITY}, so product metadata alone is not enough.
 *
 * <p>Both facts come from {@code DBMS_UTILITY.DB_VERSION} — executable by every account,
 * including through wrapping drivers whose {@link DatabaseMetaData} calls fail. When even that
 * is unavailable, the result is {@code null} and callers choose syntax valid on every release.
 */
@Component
@Slf4j
public class OracleVersionResolver {

    private static final String DB_VERSION_CALL = "{ call dbms_utility.db_version(?, ?) }";

    /**
     * Parse-only probe of the 12c identity clause. It runs an {@code ALTER TABLE} against a
     * deliberately nonexistent table through {@code DBMS_SQL.PARSE} (never executed): the
     * parser answers with ORA-00907/02000 when the grammar is unknown, and with ORA-00942
     * (table missing) when the grammar is valid but semantic resolution fails. No object is
     * created.
     */
    private static final String IDENTITY_PROBE =
            "DECLARE c INTEGER := DBMS_SQL.OPEN_CURSOR; "
            + "BEGIN BEGIN "
            + "DBMS_SQL.PARSE(c, 'ALTER TABLE JYNC_NO_SUCH_TABLE MODIFY "
            + "(\"ID\" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY)', DBMS_SQL.NATIVE); "
            + "EXCEPTION WHEN OTHERS THEN DBMS_SQL.CLOSE_CURSOR(c); RAISE; "
            + "END; DBMS_SQL.CLOSE_CURSOR(c); END;";

    private static final Pattern ORA_CODE = Pattern.compile("ORA-(\\d{4,5})");

    /** Dialect version forcing the pre-12 sequence+trigger emulation. */
    private static final Integer PRE_12_MARKER = 11;

    /**
     * Version to configure the Oracle dialect with: the effective major version when the
     * server demonstrably accepts 12c identity grammar, otherwise a pre-12 marker (or
     * {@code null}) so the dialect emits the universally-valid sequence+trigger emulation.
     *
     * <p>The extra grammar probe matters because version numbers alone can lie — a database
     * reached over an Oracle-compatible wire protocol, or a server with exotic settings, may
     * report a modern major version while still rejecting {@code AS IDENTITY}.
     */
    public Integer resolveDialectVersion(Connection conn) {
        Integer effective = resolveEffectiveMajorVersion(conn);
        if (effective == null || effective < 12) {
            return effective;
        }
        return identityGrammarAccepted(conn) ? effective : PRE_12_MARKER;
    }

    /**
     * @return effective major version, or {@code null} when neither metadata nor the PL/SQL
     *         call could answer
     */
    public Integer resolveEffectiveMajorVersion(Connection conn) {
        Integer productMajor = null;
        Integer compatibleMajor = null;

        try {
            int major = conn.getMetaData().getDatabaseMajorVersion();
            if (major > 0) {
                productMajor = major;
            }
        } catch (SQLException | RuntimeException e) {
            log.debug("JDBC metadata did not report the database version: {}", e.getMessage());
        }

        try (CallableStatement cs = conn.prepareCall(DB_VERSION_CALL)) {
            cs.registerOutParameter(1, Types.VARCHAR);
            cs.registerOutParameter(2, Types.VARCHAR);
            cs.execute();
            productMajor = firstNonNull(leadingMajor(cs.getString(1)), productMajor);
            compatibleMajor = leadingMajor(cs.getString(2));
        } catch (SQLException | RuntimeException e) {
            log.debug("DBMS_UTILITY.DB_VERSION failed: {}", e.getMessage());
        }

        if (productMajor != null && compatibleMajor != null) {
            return Math.min(productMajor, compatibleMajor);
        }
        return firstNonNull(productMajor, compatibleMajor);
    }

    /**
     * Verifies directly that the server parses the {@code AS IDENTITY} clause. Only ORA-00942
     * (the probe table does not exist — grammar was fine) and an error-free parse count as
     * accepted; parser errors, missing privileges and infrastructure failures all mean "not
     * verified", which callers treat as unsupported.
     */
    boolean identityGrammarAccepted(Connection conn) {
        try (Statement st = conn.createStatement()) {
            st.execute(IDENTITY_PROBE);
            return true;
        } catch (SQLException e) {
            if (e.getErrorCode() == 942) {
                return true;
            }
            Matcher m = ORA_CODE.matcher(String.valueOf(e.getMessage()));
            if (m.find() && Integer.parseInt(m.group(1)) == 942) {
                return true;
            }
            log.debug("Identity grammar probe did not verify the capability (vendor code {}): {}",
                    e.getErrorCode(), e.getMessage());
            return false;
        } catch (RuntimeException e) {
            log.debug("Identity grammar probe failed: {}", e.getMessage());
            return false;
        }
    }

    /** Leading numeric component of a dotted version string, e.g. "11.2.0.4.0" → 11. */
    Integer leadingMajor(String version) {
        if (version == null) {
            return null;
        }
        String head = version.trim().replaceFirst("^(\\d+).*$", "$1");
        try {
            int value = Integer.parseInt(head);
            return value > 0 ? value : null;
        } catch (NumberFormatException e) {
            return null;
        }
    }

    private static Integer firstNonNull(Integer first, Integer second) {
        return first != null ? first : second;
    }
}
